using Vora.Domain.Entities.Common;
using Vora.Domain.Entities.Media;
using Vora.Domain.Enums;

namespace Vora.Domain.Entities.Library;

public class Collection : LockableEntity
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public required string Title { get; set; }
    public string? SortTitle { get; set; }
    public string? Description { get; set; }

    public string? PosterUrl { get; set; }
    public string? BackdropUrl { get; set; }

    public int? TmdbId { get; set; }
    public string? ImdbId { get; set; }
    public string? TvdbId { get; set; }

    public bool IsAutoGenerated => TmdbId.HasValue || !string.IsNullOrEmpty(ImdbId) || !string.IsNullOrEmpty(TvdbId);
    public bool SystemGenerated { get; set; }
    public bool AutoSyncChronology { get; set; }

    public string? SortProviderId { get; set; }
    public string? ExternalListId { get; set; }
    public string? ContentSyncProviderId { get; set; }
    public string? ContentSyncExternalId { get; set; }

    public CollectionSortOrder DefaultSort { get; set; } = CollectionSortOrder.ReleaseDateDesc;

    public DateTime? VisibleStartDate { get; set; }
    public DateTime? VisibleEndDate { get; set; }

    public Guid? LibraryId { get; set; }

    public virtual ICollection<MediaItem> Items { get; set; } = new List<MediaItem>();
}
